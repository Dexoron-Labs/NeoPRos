#ifndef NEOPROS_READLINE_H
#define NEOPROS_READLINE_H

/*
 * Построчный ввод с редактированием, как в GNU readline.
 *
 * Работает поверх потока символов клавиатуры (kbd), в котором
 * расширенные клавиши уже представлены ANSI-последовательностями:
 *   стрелки        → ESC [ A/B/C/D
 *   Home/End       → ESC [ H/F
 *   Delete/Insert  → ESC [ 3~/2~
 *   PageUp/Down    → ESC [ 5~/6~
 *
 * Поддерживаются: backspace, удаление в позиции, стрелки влево/вправо,
 * Home/End, история (стрелки вверх/вниз, кольцевой буфер).
 *
 * Модуль не знает о shell: любой потребитель (prosh, будущий sh,
 * редактор) может использовать readline как самостоятельную подсистему.
 */

/* Максимальная длина строки ввода (без терминального нуля). */
#define READLINE_MAX_LEN 255

/* Число строк в кольцевой истории. */
#define READLINE_HISTORY_SIZE 16

/* Инициализация истории (очистка). */
void readline_init(void);

/*
 * Печатает prompt, читает строку до Enter.
 * Возвращает указатель на статический буфер (действителен до
 * следующего вызова). Пустая строка вернёт "".
 */
char *readline(const char *prompt);

#endif /* NEOPROS_READLINE_H */
